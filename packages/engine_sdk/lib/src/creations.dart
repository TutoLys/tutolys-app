import 'package:flutter/widgets.dart';

/// Something a child made in an engine and may want to see again: a
/// `compose_build` sentence, a `pattern_machine` pattern, a `geometry_lab`
/// shape (app ADR 0036).
///
/// Stored as the engine's own structured result, never as a picture, so the
/// engine that made it can draw it again at any size and in either theme.
class Creation {
  const Creation({
    required this.id,
    required this.engineKey,
    required this.exerciseId,
    required this.payloadVersion,
    required this.payload,
    required this.hung,
    required this.createdAt,
  });

  /// Generated by the store.
  final String id;

  /// The engine that made it, and the only one that knows how to draw it.
  final String engineKey;

  final String exerciseId;

  /// The engine's own version of [payload]'s shape, so a renderer can
  /// refuse a shape it no longer reads instead of drawing it wrong.
  final int payloadVersion;

  /// JSON-safe and owned by the engine; the store never looks inside.
  final Map<String, Object?> payload;

  /// Hung in the child's village gallery (`my_gallery`).
  final bool hung;

  final DateTime createdAt;
}

/// The active kid's creations. An engine saves to it; `my_gallery` lists
/// and hangs from it. The host binds it to one kid, so an engine never sees
/// a kid id, a database or the network: creations stay on the device (D6).
abstract interface class CreationShelf {
  /// At most this many hung at once.
  static const maxHung = 3;

  /// Largest payload accepted, as encoded JSON.
  static const maxPayloadBytes = 16 * 1024;

  /// Saves one creation. Throws [ArgumentError] if [payload] isn't
  /// JSON-encodable or encodes to more than [maxPayloadBytes].
  Future<Creation> save({
    required String engineKey,
    required String exerciseId,
    required Map<String, Object?> payload,
    int payloadVersion = 1,
  });

  /// Newest first, optionally only from [engineKeys] or only (un)hung.
  Future<List<Creation>> list({
    Set<String>? engineKeys,
    bool? hung,
    int? limit,
  });

  /// Hangs or takes down one creation. Hanging when [maxHung] are already
  /// hung throws [StateError]: the gallery asks the child which one to take
  /// down rather than the store choosing for them. Unknown ids are ignored.
  Future<void> setHung(String id, bool hung);

  /// Deletes one creation. Unknown ids are ignored.
  Future<void> remove(String id);
}

/// Puts a [CreationShelf] above an engine. Absent (a test, a host that
/// hasn't wired it), [maybeOf] is null: an engine skips saving and
/// `my_gallery` shows its empty state.
class CreationShelfScope extends InheritedWidget {
  const CreationShelfScope({
    required this.shelf,
    required super.child,
    super.key,
  });

  final CreationShelf shelf;

  static CreationShelf? maybeOf(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<CreationShelfScope>()?.shelf;

  @override
  bool updateShouldNotify(CreationShelfScope oldWidget) =>
      shelf != oldWidget.shelf;
}
